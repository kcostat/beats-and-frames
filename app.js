function applyStaticTranslations() {
  const t = I18N[currentLang];
  document.documentElement.lang = t.html_lang;
  document.title = t.meta_title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', t.meta_desc);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.setAttribute('placeholder', t[key]);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    if (t[key] !== undefined) el.setAttribute('alt', t[key]);
  });

  const subj = document.getElementById('form-subject');
  if (subj) subj.value = t.form_subject;

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

function initWork() {
  const filtersEl = document.getElementById('work-filters');
  const stageEl = document.getElementById('featured-stage');
  const stripEl = document.getElementById('thumb-strip');

  let currentCat = 'all';
  let currentList = WORKS;
  let currentIndex = 0;
  let isPlaying = false;

  function renderFilters() {
    filtersEl.innerHTML = '';
    FILTERS[currentLang].forEach(f => {
      const btn = document.createElement('button');
      btn.className = 'filter-btn' + (f.id === currentCat ? ' active' : '');
      btn.dataset.cat = f.id;
      btn.textContent = f.label;
      btn.onclick = () => setFilter(f.id);
      filtersEl.appendChild(btn);
    });
  }

  function renderStage(playing = false) {
    isPlaying = playing;
    const item = currentList[currentIndex] || currentList[0];
    const loc = item[currentLang] || item.pt;
    const t = I18N[currentLang];
    const num = String(currentIndex + 1).padStart(2, '0');
    const total = String(currentList.length).padStart(2, '0');

    stageEl.innerHTML = `
      <div class="featured-info">
        <div>
          <div class="featured-cat">${loc.label}</div>
          <h3 class="featured-title">${loc.title}</h3>
          <div class="featured-client">${loc.client}</div>
          <div class="featured-specs">${loc.specs.map(s => `| ${s}`).join('<br>')}</div>
        </div>
        <button class="play-pill" id="stage-play-btn" type="button">
          <span class="play-circle">▶</span>
          <span>${t.play_film}</span>
        </button>
      </div>
      <div class="featured-media ${playing ? 'is-playing' : ''}" id="stage-media">
        ${playing
          ? `<iframe src="https://www.youtube.com/embed/${item.id}?autoplay=1" title="${loc.title}" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen></iframe>`
          : `<img src="https://i.ytimg.com/vi/${item.id}/hqdefault.jpg" alt="${loc.title}" />`
        }
        <div class="stage-controls">
          <span>${num}<br>/<br>${total}</span>
          <button id="prev-work" type="button" aria-label="${t.prev_label}">‹</button>
          <button id="next-work" type="button" aria-label="${t.next_label}">›</button>
        </div>
      </div>
    `;

    document.getElementById('stage-play-btn').onclick = () => renderStage(true);
    document.getElementById('prev-work').onclick = () => {
      currentIndex = (currentIndex - 1 + currentList.length) % currentList.length;
      renderStage(false);
      renderThumbs();
    };
    document.getElementById('next-work').onclick = () => {
      currentIndex = (currentIndex + 1) % currentList.length;
      renderStage(false);
      renderThumbs();
    };
  }

  function renderThumbs() {
    stripEl.innerHTML = currentList.map((w, idx) => {
      const loc = w[currentLang] || w.pt;
      const num = String(idx + 1).padStart(2, '0');
      return `
        <article class="thumb-card ${idx === currentIndex ? 'active' : ''}" data-idx="${idx}">
          <div class="thumb-img-wrap">
            <span class="thumb-num">${num}</span>
            <img src="https://i.ytimg.com/vi/${w.id}/hqdefault.jpg" alt="${loc.title}" loading="lazy" />
          </div>
          <div class="thumb-client">${loc.client}</div>
          <div class="thumb-sub">${loc.title}</div>
        </article>
      `;
    }).join('');

    stripEl.querySelectorAll('.thumb-card').forEach(card => {
      card.onclick = () => {
        currentIndex = Number(card.dataset.idx);
        renderStage(true);
        renderThumbs();
        stageEl.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
      };
    });
  }

  function setFilter(catId) {
    currentCat = catId;
    currentList = catId === 'all' ? WORKS : WORKS.filter(w => w.cat === catId);
    currentIndex = 0;
    filtersEl.querySelectorAll('.filter-btn').forEach(b => {
      b.classList.toggle('active', b.dataset.cat === catId);
    });
    renderStage(false);
    renderThumbs();
  }

  document.querySelectorAll('.cat-tile').forEach(tile => {
    tile.addEventListener('click', () => setFilter(tile.dataset.cat));
  });

  renderFilters();
  renderStage(false);
  renderThumbs();

  return {
    refreshLang() {
      renderFilters();
      renderStage(isPlaying);
      renderThumbs();
    }
  };
}

async function initCatalog() {
  const res = await fetch('data/catalogo.json');
  const catalog = await res.json();
  const tabsEl = document.getElementById('series-tabs');
  const detailEl = document.getElementById('series-detail');
  let activeSeriesIdx = 0;

  function getSeriesText(s) {
    if (currentLang !== 'pt' && CATALOG_I18N[s.id] && CATALOG_I18N[s.id][currentLang]) {
      return CATALOG_I18N[s.id][currentLang];
    }
    return {
      tab: s.title.split(':')[0].replace('História do Rádio Musical — ', 'Rádio '),
      badge: s.badge,
      title: s.title,
      subtitle: s.subtitle,
      description: s.description
    };
  }

  function renderSeries(idx) {
    activeSeriesIdx = idx;
    const s = catalog[idx];
    if (!s) return;
    const st = getSeriesText(s);
    const t = I18N[currentLang];
    const modeLabel = s.legal_mode === 'rss_direct' ? t.mode_rss : t.mode_embed;

    const epsHtml = s.episodes.map(ep => {
      const img = ep.cover ? `<img class="ep-cover" src="${ep.cover}" alt="${ep.title}" loading="lazy" />` : '';
      const items = ep.items.slice(0, 10).map(it => `<li>${it.title}</li>`).join('');
      return `
        <article class="ep-card">
          ${img}
          <div class="ep-body">
            <div class="ep-code">${ep.code} • ${s.lang}</div>
            <h4 class="ep-title">${ep.title}</h4>
            <ol class="ep-list">${items}</ol>
            <div class="ep-footer">${modeLabel}</div>
          </div>
        </article>
      `;
    }).join('');

    const audioSection = document.getElementById('audioseries');
    if (audioSection) {
      audioSection.className = `audio-section page-view ${audioSection.classList.contains('active') ? 'active' : ''} theme-${s.id}`;
    }

    detailEl.innerHTML = `
      <div class="series-banner">
        <span class="badge">${st.badge} • ${s.lang}</span>
        <h3>${st.title}</h3>
        <div>${st.subtitle}</div>
        <p>${st.description}</p>
      </div>
      <div class="ep-grid">${epsHtml}</div>
    `;
    const envEl = document.getElementById('series-env');
    if (envEl && window.renderSeriesEnvironment) {
      window.renderSeriesEnvironment(envEl, s.id, currentLang);
    }
  }

  function renderTabs() {
    tabsEl.innerHTML = '';
    catalog.forEach((s, idx) => {
      const st = getSeriesText(s);
      const btn = document.createElement('button');
      btn.className = 'filter-btn' + (idx === activeSeriesIdx ? ' active' : '');
      btn.textContent = st.tab;
      btn.onclick = () => {
        tabsEl.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        renderSeries(idx);
      };
      tabsEl.appendChild(btn);
    });
  }

  if (catalog.length) {
    renderTabs();
    renderSeries(0);
  }

  return {
    refreshLang() {
      if (!catalog.length) return;
      renderTabs();
      renderSeries(activeSeriesIdx);
    },
    selectById(id) {
      const idx = catalog.findIndex(s => s.id === id);
      if (idx >= 0) {
        activeSeriesIdx = idx;
        renderTabs();
        renderSeries(idx);
      }
    }
  };
}

function navigateTo(pageId, updateHash = true) {
  let targetPage = pageId || 'home';
  let seriesId = null;
  if (targetPage.startsWith('serie-')) {
    seriesId = targetPage.slice(6);
    targetPage = 'audioseries';
  }
  const views = document.querySelectorAll('.page-view');
  const valid = Array.from(views).some(v => v.dataset.page === targetPage);
  if (!valid) targetPage = 'home';

  views.forEach(v => v.classList.toggle('active', v.dataset.page === targetPage));
  document.body.classList.toggle('is-inner', targetPage !== 'home');
  document.querySelectorAll('[data-page-link]').forEach(a => {
    a.classList.toggle('active-nav', a.dataset.pageLink === targetPage);
  });

  if (seriesId && catalogApi) catalogApi.selectById(seriesId);
  if (updateHash) {
    const newHash = seriesId ? `#serie-${seriesId}` : `#${targetPage}`;
    if (window.location.hash !== newHash) history.pushState(null, '', newHash);
  }
  window.scrollTo({ top: 0, behavior: 'instant' });
}

document.querySelectorAll('[data-page-link]').forEach(link => {
  link.addEventListener('click', e => {
    e.preventDefault();
    navigateTo(link.dataset.pageLink);
  });
});

window.addEventListener('hashchange', () => {
  const h = window.location.hash.replace('#', '') || 'home';
  navigateTo(h, false);
});

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('bf_lang', lang);
  applyStaticTranslations();
  if (workApi) workApi.refreshLang();
  if (catalogApi) catalogApi.refreshLang();
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

